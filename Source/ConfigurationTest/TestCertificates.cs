using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;

namespace ROOT.Etcd.ConfigurationTest;

/// <summary>
/// Ensures the self-signed test certificates used by the TLS integration tests exist
/// and are not older than one day.
/// </summary>
public static class TestCertificates
{
    private const string DefaultDockerImage = "alpine:3.20";
    private const string GenerateScript = "generate-certs.sh";

    private static readonly TimeSpan MaximumCertificateAge = TimeSpan.FromDays(1);
    private static readonly string[] GeneratedFiles = ["ca.crt", "server.crt", "server.key"];
    private static readonly string[] GenerationArtifacts =
    [
        "ca.crt", "ca.key", "server.crt", "server.key", "ca.srl", "server.csr", "server.ext"
    ];

    private static readonly object Gate = new();
    private static bool _checked;

    public static string SourceDirectory { get; } = FindSourceDirectory();

    public static string CertificateDirectory { get; } = Path.Combine(SourceDirectory, "certs");

    public static string CaCertificatePath { get; } = Path.Combine(CertificateDirectory, "ca.crt");

    /// <summary>
    /// Gets whether the certificates were regenerated by this process.
    /// Used to force the TLS etcd container to reload the new certificate.
    /// </summary>
    public static bool WasRegenerated { get; private set; }

    /// <summary>
    /// Generates the certificates when they are missing or older than one day.
    /// The check and generation run only once per test assembly/process.
    /// </summary>
    public static void EnsureGenerated()
    {
        lock (Gate)
        {
            if (_checked)
            {
                return;
            }

            WasRegenerated = !CertificatesAreCurrent();
            if (WasRegenerated)
            {
                GenerateCertificates();
            }

            _checked = true;
        }
    }

    private static bool CertificatesAreCurrent()
    {
        var oldestAllowed = DateTime.UtcNow - MaximumCertificateAge;
        var scriptPath = Path.Combine(CertificateDirectory, GenerateScript);
        var scriptTimestamp = File.Exists(scriptPath) ? File.GetLastWriteTimeUtc(scriptPath) : DateTime.MinValue;

        foreach (var fileName in GeneratedFiles)
        {
            var filePath = Path.Combine(CertificateDirectory, fileName);
            if (!File.Exists(filePath))
            {
                return false;
            }

            var timestamp = File.GetLastWriteTimeUtc(filePath);
            if (timestamp < oldestAllowed || timestamp < scriptTimestamp)
            {
                return false;
            }
        }

        return true;
    }

    private static void GenerateCertificates()
    {
        Directory.CreateDirectory(CertificateDirectory);

        // Remove partial output so a failed generation is retried next time.
        foreach (var artifact in GenerationArtifacts)
        {
            File.Delete(Path.Combine(CertificateDirectory, artifact));
        }

        if (OperatingSystem.IsWindows())
        {
            GenerateCertificatesInDocker();
        }
        else
        {
            RunProcess(
                "bash",
                [GenerateScript],
                CertificateDirectory,
                "native openssl");
        }
    }

    /// <summary>
    /// Windows usually has neither bash nor openssl, so run the script in a small
    /// Alpine container with the certificate directory bind-mounted.
    /// </summary>
    private static void GenerateCertificatesInDocker()
    {
        var image = Environment.GetEnvironmentVariable("ETCD_TLS_CERT_DOCKER_IMAGE") ?? DefaultDockerImage;
        var certificateDirectory = Path.GetFullPath(CertificateDirectory);

        RunProcess(
            "docker",
            [
                "run", "--rm",
                "-v", $"{certificateDirectory}:/certs",
                "-w", "/certs",
                image,
                "sh", "-c",
                $"apk add --no-cache bash openssl >/dev/null && bash {GenerateScript}"
            ],
            CertificateDirectory,
            "docker");
    }

    private static void RunProcess(
        string fileName,
        IReadOnlyList<string> arguments,
        string workingDirectory,
        string description)
    {
        var startInfo = new ProcessStartInfo(fileName)
        {
            WorkingDirectory = workingDirectory,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false
        };

        foreach (var argument in arguments)
        {
            startInfo.ArgumentList.Add(argument);
        }

        using var process = Process.Start(startInfo)
            ?? throw new InvalidOperationException(
                $"Could not start the TLS certificate generator ({description}).");

        var standardOutput = process.StandardOutput.ReadToEnd();
        var standardError = process.StandardError.ReadToEnd();
        process.WaitForExit();

        if (process.ExitCode != 0)
        {
            throw new InvalidOperationException(
                $"TLS certificate generation failed ({description}) with exit code {process.ExitCode}." +
                Environment.NewLine +
                standardOutput +
                Environment.NewLine +
                standardError);
        }
    }

    private static string FindSourceDirectory()
    {
        var directory = new FileInfo(typeof(TestCertificates).Assembly.Location).Directory;
        while (directory != null && directory.Name != "Source")
        {
            directory = directory.Parent;
        }

        return directory?.FullName
            ?? throw new InvalidOperationException("Could not determine the Source directory.");
    }
}
